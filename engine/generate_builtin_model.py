"""Embed a binary asset into a C header as a byte array.

The engine's built-in assets (see engine/core/io/BuiltinModel.cpp) must live in
the engine binary itself, so a project that has no copy of the file still renders
it. Format follows the existing precedent (editor/resources/fonts/*_ttf.h,
produced by `xxd -i`): a plain initializer list.

A base64 string literal looks cheaper to write but MSVC folds the whole
17k-literal concatenation into one token and dies with C1060 (compiler heap).

Usage: generate_builtin_model.py <asset-file> <out-header> <symbol-name>
"""
import os
import sys

BYTES_PER_LINE = 12  # matches the font headers, keeps one entry per column


def main(argv):
    if len(argv) != 4:
        print(__doc__.strip().splitlines()[-1])
        return 2

    asset_path, out_path, symbol = argv[1], argv[2], argv[3]

    with open(asset_path, "rb") as handle:
        raw = handle.read()

    lines = [
        "// (c) SR VINIX",
        "// SPDX-License-Identifier: MIT",
        "",
        "// GENERATED by engine/generate_builtin_model.py - do not edit.",
        "// Source: %s (%d bytes)" % (
            asset_path.replace(os.sep, "/"), len(raw)),
        "// Rerun the script after changing the asset.",
        "",
        "#pragma once",
        "",
        "static const unsigned char %s_data[] = {" % symbol,
    ]

    for index in range(0, len(raw), BYTES_PER_LINE):
        chunk = raw[index:index + BYTES_PER_LINE]
        last = index + BYTES_PER_LINE >= len(raw)
        body = ",".join("0x%02x" % byte for byte in chunk)
        lines.append("    %s%s" % (body, "" if last else ","))

    lines += [
        "};",
        "",
        "static const unsigned long long %s_size = %dull;" % (symbol, len(raw)),
        "",
    ]

    out_dir = os.path.dirname(os.path.abspath(out_path))
    if out_dir:
        os.makedirs(out_dir, exist_ok=True)
    with open(out_path, "w", encoding="utf-8", newline="\n") as handle:
        handle.write("\n".join(lines))

    print("wrote %s (%d bytes, %d entries)" % (
        out_path, len(raw), len(raw)))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
